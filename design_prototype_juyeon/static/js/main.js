// =========================================================
// APPLY LANGUAGE
// =========================================================

function applyLanguage(language) {

    currentLanguage = language;

    localStorage.setItem(
        "axp-language",
        language
    );


    // HTML lang 속성
    document.documentElement.lang =
        language === "zh"
            ? "zh-CN"
            : language;


    // 일반 텍스트
    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const key =
                element.dataset.i18n;

            const value =
                translations[language][key];

            if (value) {
                element.textContent =
                    value;
            }

        });


    // HTML 줄바꿈이 있는 텍스트
    document
        .querySelectorAll("[data-i18n-html]")
        .forEach((element) => {

            const key =
                element.dataset.i18nHtml;

            const value =
                translations[language][key];

            if (value) {
                element.innerHTML =
                    value;
            }

        });


    currentLanguageLabel.textContent =
        languageLabels[language];

    desktopLanguage.textContent =
        languageLabels[language];


    // 현재 선택된 비즈니스 정보도 번역
    activateBusiness(
        currentBusiness,
        false
    );

}



